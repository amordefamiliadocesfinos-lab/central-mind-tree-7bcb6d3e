#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),ts=require("typescript"),vm=require("node:vm"),assert=require("node:assert/strict");
const path="supabase/functions/_shared/nucleo/ac02-write-preflight.ts";
const js=ts.transpileModule(fs.readFileSync(path,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const ctx={exports:{},require:()=>({}),Object,Set,Date,Number};
vm.runInNewContext(js,ctx,{timeout:1500});
const check=ctx.exports.preflightAc02WriteCandidate;
const ids={packageId:"11111111-1111-4111-8111-111111111111",moduleId:"22222222-2222-4222-8222-222222222222",requestId:"33333333-3333-4333-8333-333333333333",previous:"44444444-4444-4444-8444-444444444444",recipient:"55555555-5555-4555-8555-555555555555"};
const manifest={kind:"nucleo_ac02_package_manifest",packageId:ids.packageId,packageVersion:"1.0",packageSha256:"a".repeat(64),recipientKind:"sucessor_humano",recipientAuthUid:ids.recipient,provenance:"local_computed_not_authenticated",delivered:false,accepted:false};
const base={packageId:ids.packageId,moduleId:ids.moduleId,requestId:ids.requestId,packageVersion:"1.0",packageSha256:"a".repeat(64),specialistRoleCode:"especialista_crm",recipientKind:"sucessor_humano",recipientAuthUid:ids.recipient,eventKind:"preparado",previousEventId:null,evidenceClass:"declaracao_gestor",evidenceRef:null,sourceRef:"ac02:pacote:v1",expiresAt:"2026-11-15T12:00:00Z"};
const pass=check(base,manifest);
assert.equal(pass.state,"candidate_only_no_authority");
for(const k of ["sessionVerified","capabilityVerified","evidenceVerified","packageOriginVerified","writesPerformed"])assert.equal(pass[k],false);
const bad=(v,m=manifest)=>assert.equal(check({...base,...v},m).state,"rejected");
bad({packageSha256:"b".repeat(64)});
bad({packageId:"nope"});
bad({recipientAuthUid:null});
bad({eventKind:"entregue",previousEventId:ids.previous,evidenceRef:null});
bad({eventKind:"recebido",previousEventId:ids.previous,evidenceClass:"declaracao_gestor"});
bad({eventKind:"aceito",previousEventId:ids.previous,evidenceClass:"confirmacao_destinatario",recipientKind:"novo_chat_ia",recipientAuthUid:null});
bad({eventKind:"expirado",previousEventId:null});
bad({eventKind:"falha",previousEventId:ids.previous,evidenceRef:"https://secret?token=x"});
bad({eventKind:"retificado",previousEventId:ids.previous,evidenceRef:null});
bad({}, {...manifest,provenance:"verified"});
const success=check({...base,eventKind:"recebido",previousEventId:ids.previous,evidenceClass:"confirmacao_destinatario"},manifest);
assert.equal(success.state,"candidate_only_no_authority");
assert.equal(success.sessionVerified,false);
const source=fs.readFileSync(path,"utf8");
assert.ok(!/\.insert\(|\.update\(|\.upsert\(|\.delete\(|\.rpc\(|fetch\(/.test(source));
console.log("PASS AC02 preflight: shape only; no authority, session or delivery claims");
