"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),ts=require("typescript"),vm=require("node:vm");
const source=fs.readFileSync("src/lib/nucleo/executiveSupervisionV1.ts","utf8");
const box={exports:{}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,box);
const {findExecutiveWorkstream,executivePriorityLabel,orderExecutiveFindings,summarizeExecutiveFindings}=box.exports;
const fronts=Object.freeze([{id:"1",code:"A",kind:"frente",priority:"normal"},{id:"2",code:"B",kind:"frente",priority:"critica"},{id:"3",code:"C",kind:"frente",priority:"alta"},{id:"4",code:"ROOT",kind:"modulo",priority:"critica"}].map(Object.freeze));
const finding=(id,workstreamCode,severity)=>Object.freeze({id,workstreamCode,severity,evidenceIds:Object.freeze([id])});
const findings=Object.freeze([finding("i","B","informativo"),finding("a","A","atencao"),finding("c","C","atencao"),finding("b","B","atencao"),finding("d","C","atencao"),finding("x","missing","atencao")]);
const sorted=orderExecutiveFindings(findings,fronts);
assert.deepEqual(Array.from(sorted,x=>x.id),["b","c","d","a","x","i"]);
assert(sorted.every(x=>findings.includes(x)));
assert.equal(findings[0].id,"i");
assert.equal(findExecutiveWorkstream("ROOT",fronts),undefined);
assert.equal(findExecutiveWorkstream("B",[...fronts,{...fronts[1],id:"duplicate"}]),undefined);
assert.equal(executivePriorityLabel("critica"),"Crítica");
assert.equal(executivePriorityLabel("unknown"),"Não identificada");
const summary=summarizeExecutiveFindings(findings);
assert.equal(summary.attention,5);assert.equal(summary.information,1);assert.equal(summary.workstreams,4);
assert.equal(summarizeExecutiveFindings([]).attention,0);
const ui=fs.readFileSync("src/components/nucleo/NucleoSupervisionPanel.tsx","utf8");
assert(ui.includes("orderExecutiveFindings(focusModuleId ? snapshot.findings.filter"));
assert(ui.includes('const complete = loaded && permissionConfirmed && !loadError'));
assert(ui.includes('inspectNucleoSupervision(latestFronts, evidence, latestDependencies'));
assert(ui.includes("Prioridade registrada:"));
assert(ui.includes("Responsável declarado:"));
assert(ui.includes("Próxima ação registrada e detalhes"));
assert(ui.includes("front.next_action.trim()?front.next_action"));
assert(ui.includes("excerpt&&excerpt.length<=480"));
assert(ui.includes("onClick={()=>onOpenWorkstream(front.id)}"));
assert(ui.includes("onClick={()=>onOpenEvidence(front.id)}"));
assert(ui.includes("findNucleoFindingSources(finding, evidence)"));
assert(!source.includes("supabase"));
console.log("PASS SI05: original findings and evidence preserved, ordering only, scope, ambiguity and action provenance");
