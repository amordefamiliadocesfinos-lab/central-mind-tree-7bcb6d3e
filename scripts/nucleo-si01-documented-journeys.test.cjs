"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),ts=require("typescript"),vm=require("node:vm");
const source=fs.readFileSync("src/lib/nucleo/documentedJourneysV1.ts","utf8");
const box={exports:{}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,box);
const {documentedJourneys}=box.exports;
const root=(code,id=code)=>({code,id,title:code,kind:"modulo"});
const roots=["NUC","OPE","FIN","DIG","CRM","CAP","ROT","ASS","SAU","SHO"].map(code=>root(code));
const snapshot=Object.freeze(roots.map(Object.freeze));
const result=documentedJourneys(snapshot);
assert.equal(result.length,5);
assert.deepEqual(Array.from(result,x=>x.key),["purchase","campaign","capture","routine","assistant"]);
for(const row of result){
 assert(row.source.startsWith("https://github.com/amordefamiliadocesfinos-lab/central-mind-tree-7bcb6d3e/issues/1037#issuecomment-"));
 assert(row.modules.every(m=>snapshot.includes(m)));
 assert(row.next.length>10);
}
assert.equal(documentedJourneys(snapshot,"FIN").length,1);
assert.equal(documentedJourneys(snapshot,"FIN")[0].key,"purchase");
assert.equal(documentedJourneys(snapshot,"CRM")[0].key,"campaign");
assert.equal(documentedJourneys(snapshot,"SHO").length,0);
assert.equal(documentedJourneys(snapshot,"missing").length,0);
assert.equal(documentedJourneys([]).length,0);
assert(!documentedJourneys(snapshot.filter(x=>x.code!=="FIN")).some(x=>x.key==="purchase"));
assert(!documentedJourneys([...snapshot,root("FIN","other")]).some(x=>x.key==="purchase"));
assert(!documentedJourneys([...snapshot.filter(x=>x.code!=="FIN"),{...root("FIN"),kind:"frente"}]).some(x=>x.key==="purchase"));
assert(!source.includes("supabase")&&!source.includes(".insert(")&&!source.includes(".update("));
