const authorized=ui.indexOf("{snapshot && (");
const panel=ui.indexOf("Conexões entre áreas",authorized);
const demo=ui.indexOf("Laboratório visual de alertas",panel);
assert(authorized>=0&&panel>authorized&&demo>panel);
assert(ui.includes("documentedJourneys(latestFronts,focusModuleId)"));
assert(ui.includes("onOpenWorkstream(module.id)"));
assert(ui.includes("Não são dependências bloqueantes cadastradas, alertas ou confirmação de execução."));
assert(ui.includes("Isso não significa que não existam conexões."));
assert(ui.includes("inspectNucleoSupervision(latestFronts, evidence, latestDependencies"));
assert(ui.includes("const complete = loaded && permissionConfirmed && !loadError"));
console.log("PASS SI01: documented journeys, authorized roots, focused scope, missing/ambiguous modules, separation from dependency/alert rules");
