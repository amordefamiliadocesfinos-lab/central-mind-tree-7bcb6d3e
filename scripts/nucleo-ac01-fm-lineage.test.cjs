#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),ts=require("typescript");
const file="src/lib/nucleo/ac01FmLineageV13.ts";
const source=fs.readFileSync(file,"utf8");
const mod=ts.transpileModule(source,{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.equal(mod.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length??0,0);
const fmMod=ts.transpileModule(fs.readFileSync("src/lib/nucleo/ac01FmSourceMatchV13.ts","utf8"),{fileName:"match.ts",compilerOptions:{module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
const match={exports:{}};
new Function("module","exports",fmMod.outputText)(match,match.exports);
const lineage={exports:{}};
new Function("module","exports","require",mod.outputText)(lineage,lineage.exports,()=>match.exports);
const build=lineage.exports.buildAc01FmLineage;
const base={module_id:"crm",lineage_id:"l1",specialist_role:"CRM",contribution_kind:"manual",recorded_by_auth_uid:"actor"};
const v1={...base,id:"a",version_no:1,parent_revision_id:null,source_locator:"docs/manual",authority_state:"proposta",recorded_at:"2026-11-01T00:00:00Z"};
const v2={...base,id:"b",version_no:2,parent_revision_id:"a",source_locator:"docs/manual",authority_state:"em_evolucao",recorded_at:"2026-11-02T00:00:00Z"};
const req={id:"req",contribution_id:"b",requested_outcome:"aprovar",recorded_at:"2026-11-03T00:00:00Z"};
const dec={id:"dec",contribution_id:"b",decision_request_id:"req",outcome:"aprovada",recorded_at:"2026-11-04T00:00:00Z"};
const pub={id:"pub",contribution_id:"b",decision_act_id:"dec",recorded_at:"2026-11-05T00:00:00Z"};
const f={id:"fm",module_id:"crm",section_code:"FM-07",version_no:3,source_reference:"docs/manual",authority_state:"rascunho"};
let out=build(v2,[v1,v2,{...v1,id:"other",module_id:"financeiro",lineage_id:"l1"}],[req],[dec],[pub],[f,{...f,id:"foreign",module_id:"financeiro"}]);
assert.deepEqual(out.entries.map(x=>x.id),["a","b"]);
assert.equal(out.entries[1].requests.length,1);
assert.equal(out.entries[1].decisions.length,1);
assert.equal(out.entries[1].publications[0].chainConfirmed,true);
assert.equal(out.fmCandidates.length,1);
assert.equal(out.fmCandidates[0].match,"localizador_identico");
assert.equal(out.fmHasPersistentLink,false);
assert.equal(out.externalPublicationVerified,false);
out=build(v2,[v2],[req],[dec],[pub],[f]);
assert(out.issues.some(x=>x.includes("anterior")||x.includes("Anterior")||x.includes("Início")));
out=build(v2,[v1,v2],[req],[],[pub],[f]);
assert.equal(out.entries[1].publications[0].chainConfirmed,false);
assert(out.issues.some(x=>x.includes("publicação interna")));
out=build(v2,[v1,v2],[],[dec],[pub],[f]);
assert.equal(out.entries[1].decisions.length,0);
assert.equal(out.entries[1].publications[0].chainConfirmed,false);
const ui=fs.readFileSync("src/components/nucleo/NucleoAC01DocumentGovernance.tsx","utf8");
assert(ui.includes("buildAc01FmLineage(selected,contributions,reqs,decisions,publications,fm)"));
assert(ui.includes("lineage.issues.map("));
assert(ui.includes("lineage.fmCandidates.map("));
assert(ui.includes("NÃO possuem vínculo persistido"));
assert(!/\.insert\(|\.update\(|\.upsert\(|\.delete\(|\.rpc\(/.test(source),"Projection cannot write");
console.log("AC01↔FM lineage: explicit IDs, incomplete-chain warnings, no false FM or external publication links");
